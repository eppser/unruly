-- ---------------------------------------------------------------------------
-- Twenty filler relations, half of them readable. Generated rather than typed
-- out: their names and counts are decided by one rule, so there is no chance
-- of a silent transcription error, and the rule is visible.
--
-- i odd  -> GRANT SELECT (10 relations)
-- i even -> no grant     (10 relations)
-- rows    = 3 + (i % 6)
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  names text[] := ARRAY[
    'inventory','shipments','warehouses','suppliers','categories',
    'reviews','coupons','refunds','taxes','currencies',
    'regions','locales','templates','campaigns','segments',
    'exports','imports','jobs','queues','metrics'];
  i  int;
  nm text;
BEGIN
  FOR i IN 1..array_length(names, 1) LOOP
    nm := names[i];
    EXECUTE format(
      'CREATE TABLE public.%I (id bigserial PRIMARY KEY, label text NOT NULL, '
      'note text, recorded_at timestamptz NOT NULL DEFAULT now())', nm);
    EXECUTE format(
      'INSERT INTO public.%I (label, note) SELECT %L || ''-'' || g, ''row '' || g '
      'FROM generate_series(1, %s) g', nm, nm, 3 + (i % 6));
    IF i % 2 = 1 THEN
      EXECUTE format('GRANT SELECT ON public.%I TO anon, authenticated', nm);
    END IF;
  END LOOP;
END $$;

-- ---------------------------------------------------------------------------
-- Privileges for the hand-written tables.
