-- ---------------------------------------------------------------------------
-- RLS enabled, no policy: a SELECT grant and an empty result, forever. Under a
-- throttle this is the nastiest of the three states, because "200 and []" and
-- "429, try again" both mean "no rows arrived" to anything counting rows.
-- ---------------------------------------------------------------------------
