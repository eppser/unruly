-- Project 08: a real schema behind a real rate limit.
--
-- The schema itself is deliberately ordinary. Its only job is to be big enough
-- that a scan needs many requests to cover it -- 30 relations, a mix of open,
-- REVOKE-protected and RLS-with-no-policy -- so that the throttle in
-- conf/throttle.conf has something to bite on. The measurement is what happens
-- to the RELATION LIST when a fraction of the probes are refused, not what is
-- in any particular table.
--
-- Ten of these tables are written out because their CONTENT matters: a scan
-- that gets through to user_credentials and one that gets 429 on it are the
-- same scan with very different reports. The other twenty are generated by a
-- DO block, because thirty hand-written filler tables is thirty chances to
-- make a typo that nobody would ever notice.

